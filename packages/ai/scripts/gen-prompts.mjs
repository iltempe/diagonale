// Generates src/prompts.generated.ts from prompts/*.md so the prompts work in browser and Node alike.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'prompts');
const entries = readdirSync(dir)
  .filter((f) => f.endsWith('.md'))
  .sort()
  .map((f) => [f.replace(/\.md$/, ''), readFileSync(join(dir, f), 'utf8')]);
const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
const out = `// AUTO-GENERATED by scripts/gen-prompts.mjs from prompts/*.md — do not edit.\nexport const PROMPTS: Record<string, string> = {\n${body}\n};\n`;
writeFileSync(join(root, 'src/prompts.generated.ts'), out);
