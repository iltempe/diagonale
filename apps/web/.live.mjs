import { chromium } from '@playwright/test';
const b = await chromium.launch();
const p = await b.newPage({ locale: 'it-IT', viewport: { width: 1280, height: 900 } });
const counts = []; p.on('request', (r) => r.url().includes('goatcounter.com/count') && counts.push(new URL(r.url()).searchParams.get('p')));
await p.goto('https://iltempe.github.io/diagonale/');
await p.waitForTimeout(2500);
console.log('goatcounter hits sent:', counts);
console.log('badge link:', (await p.inputValue('#badge-code')).match(/href="([^"]+)"/)[1]);
await p.selectOption('#badge-kind', 'img');
await p.waitForTimeout(800);
console.log('badge image loads:', await p.locator('.badge-preview img').evaluate((i) => i.naturalWidth));
console.log('share url in whatsapp:', decodeURIComponent((await p.locator('[data-share=whatsapp]').getAttribute('href')).split('%20').pop()));
await p.locator('[data-share=copy]').click().catch(() => {});
await p.waitForTimeout(800);
console.log('click events sent:', counts.filter((c) => !c?.startsWith('/')));
console.log('README gif:', (await (await fetch('https://raw.githubusercontent.com/iltempe/diagonale/main/docs/screenshots/demo.gif')).status));
await b.close();
